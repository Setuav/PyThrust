def solve_case(name, propeller):
    motor, battery, soc, system, diameter_m, airspeed_mps, throttle = CASES[name]
    if battery == "rate_map":
        battery = _rate_map_pack()
    return PropulsionSolver().solve_operating_point(
        motor=motor or CATALOG_MOTOR,
        battery=battery,
        system=system,
        propeller=propeller if diameter_m is None else propeller.scaled(diameter_m),
        rho=1.225,
        airspeed_mps=airspeed_mps,
        throttle=throttle,
        battery_state=None if soc is None else BatteryState(soc=soc),
    )


def solve_bus(propeller):
    network = BatteryNetwork.single(_rate_map_pack())
    units = [
        PropulsionUnit(
            motor=CATALOG_MOTOR,
            propeller=propeller,
            system=SystemSpec(0.015),
        ),
        PropulsionUnit(
            motor=SECOND_ORDER_MOTOR,
            propeller=propeller.scaled(0.28),
            system=SystemSpec(0.02),
        ),
    ]
    bus = BusSolver().solve(network, network.full_state(), units, [0.7, 0.5], rho=1.225, airspeed_mps=6.0)
    return {
        "voltage_v": bus.voltage_v,
        "current_a": bus.current_a,
        "thrust_n": bus.thrust_n,
        "is_feasible": bus.is_feasible,
        "infeasible_reason": bus.infeasible_reason,
        "unit_rpm": [unit.rpm for unit in bus.units],
        "unit_battery_current_a": [unit.battery_current_a for unit in bus.units],
    }


def _assert_matches(actual, expected):
    assert actual.keys() == expected.keys()
    for field, value in expected.items():
        if isinstance(value, (bool, str)) or value is None:
            assert actual[field] == value, field
        else:
            assert actual[field] == pytest.approx(value, rel=REL_TOL, abs=1e-12), field


@pytest.mark.parametrize("name", sorted(CASES))
def test_operating_point_matches_golden(name, propeller):
    _assert_matches(asdict(solve_case(name, propeller)), GOLDEN[name])


def test_bus_matches_golden(propeller):
    _assert_matches(solve_bus(propeller), GOLDEN_BUS)
